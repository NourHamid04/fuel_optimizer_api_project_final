"""
Fuel Route Optimizer API Configuration

This module initializes the Django Ninja API instance
and registers all application routers.

The API provides endpoints for:
- Route calculation
- Fuel optimization
- Cost estimation

API documentation is automatically generated by Ninja:
    /api/docs
"""



from ninja import NinjaAPI

from .routers.routes import router



# ============================================================
# API Configuration
# ============================================================


api = NinjaAPI(

    # API title displayed in Swagger documentation
    title="Fuel Route Optimizer API",


    # Current API version
    version="1.0.0",


    # Description shown in OpenAPI docs
    description="""
    API that calculates optimal fuel stops
    along a driving route.

    Features:
    - Route generation using OSRM
    - Fuel station optimization
    - Cheapest fuel selection
    - Total fuel cost calculation

    Vehicle assumptions:
    - Maximum range: 500 miles
    - Fuel efficiency: 10 MPG
    """
)



# ============================================================
# Router Registration
# ============================================================


# All route optimization endpoints
# will be available under:

# /api/routes/

api.add_router(
    "/routes/",
    router
)